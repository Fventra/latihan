# Deskripsi Masalah:
# Sebuah tempat parkir menentukan tarif berdasarkan jenis
# kendaraan dan lama kendaraan berada di tempat parkir.
#
# Spesifikasi Program:
#
# Input:
# - Jenis kendaraan ("motor" atau "mobil")
# - Lama parkir dalam jam (bilangan bulat)
#
# Tarif:
#
# Motor:
# - Jika lama parkir <= 2 jam, tarif = Rp3.000
# - Jika lama parkir > 2 jam, tarif = Rp5.000
#
# Mobil:
# - Jika lama parkir <= 2 jam, tarif = Rp5.000
# - Jika lama parkir > 2 jam, tarif = Rp10.000
#
# Proses:
# - Tentukan biaya parkir berdasarkan jenis kendaraan
#   dan lama parkir.
#
# - Buat variabel boolean "parkir_lama".
#   True jika lama parkir > 5 jam.
#   False jika lama parkir <= 5 jam.
#
# Output:
# - Jenis kendaraan
# - Lama parkir
# - Total biaya parkir
# - Status parkir lama
#
# KAMUS:
# jenis : string
# lama : int
# biaya : int
# parkir_lama : bool
#
# ALGORITMA:
# 1. Input jenis kendaraan.
# 2. Input lama parkir.
# 3. Tentukan biaya berdasarkan jenis kendaraan
#    dan lama parkir.
# 4. Tentukan nilai parkir_lama.
# 5. Tampilkan hasil.
# ============================================================


