# Deskripsi Masalah:
# Seorang mahasiswa ingin menghitung total pengeluaran
# bulanannya. Pengeluaran terdiri dari biaya makan,
# transportasi, internet, dan kebutuhan lainnya.
#
# Spesifikasi Program:
#
# Input:
# - Biaya makan selama sebulan (Rupiah, bilangan bulat)
# - Biaya transportasi selama sebulan (Rupiah, bilangan bulat)
# - Biaya internet selama sebulan (Rupiah, bilangan bulat)
# - Biaya kebutuhan lainnya (Rupiah, bilangan bulat)
# - Nama mahasiswa (teks)
#
# Proses:
# - Hitung total pengeluaran.
#   Rumus:
#   total = makan + transportasi + internet + lainnya
#
# - Buat variabel boolean "pengeluaran_besar".
#   True jika total pengeluaran > Rp2.000.000.
#   False jika total pengeluaran <= Rp2.000.000.
#
# Output:
# - "Halo, [Nama]!"
# - "Total Pengeluaran: Rp [total]"
# - "Apakah pengeluaran besar? [pengeluaran_besar]"
#
# KAMUS:
# makan, transportasi, internet, lainnya, total : int
# nama : string
# pengeluaran_besar : bool
#
# ALGORITMA:
# 1. Input nama mahasiswa.
# 2. Input biaya makan.
# 3. Input biaya transportasi.
# 4. Input biaya internet.
# 5. Input biaya kebutuhan lainnya.
# 6. Hitung total pengeluaran.
# 7. Tentukan nilai pengeluaran_besar.
# 8. Tampilkan hasil.
