#
# Buat variabel boolean "lulus":
# - True jika nilai akhir >= 65
# - False jika nilai akhir < 65
#
# Output:
# - Nama mahasiswa
# - Nilai akhir
# - Status kelulusan
#
# KAMUS:
# nama : string
# tugas, uts, uas, nilai_akhir : float
# lulus : bool
#
# ALGORITMA:
# 1. Input nama mahasiswa.
# 2. Input nilai tugas.
# 3. Input nilai UTS.
# 4. Input nilai UAS.
# 5. Hitung nilai akhir.
# 6. Tentukan apakah mahasiswa lulus.
